test("Skills use only trusted .agents sources, resolve precedence, and persist path-based disable", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "arkcode-skills-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const userHome = join(root, "user");
  const home = join(root, "config");
  const repo = join(root, "repo");
  const cwd = join(repo, "child");
  await mkdir(cwd, { recursive: true }); await mkdir(join(repo, ".git"));
  async function skill(base: string, name: string, body: string) {
    const dir = join(base, name); await mkdir(dir, { recursive: true });
    const file = join(dir, "SKILL.md");
    await writeFile(file, `---\nname: ${name}\ndescription: ${name} workflow.\n---\n${body}`);
    return file;
  }
  const project = await skill(join(cwd, ".agents", "skills"), "review", "Project body.");
  const global = await skill(join(userHome, ".agents", "skills"), "review", "User body.");
  await skill(join(repo, ".agents", "skills"), "ancestor", "Ancestor body.");
  await skill(join(cwd, ".pi", "skills"), "pi-sentinel", "Do not load.");
  await skill(join(userHome, ".pi", "skills"), "user-pi-sentinel", "Do not load.");
  await skill(join(home, "skills"), "brand-sentinel", "Do not load.");
  await skill(join(root, ".agents", "skills"), "outside-sentinel", "Do not load.");
  const manager = new SkillsManager({ home, cwd, trusted: true, userHome });
  assert.deepEqual(manager.available.map((item) => item.name), ["review", "ancestor"]);
  assert.equal(manager.available[0]?.path, project);
  assert.ok(manager.items.find((item) => item.path === global)?.shadowed);
  assert.throws(() => manager.setEnabled("review", false), /Ambiguous/);
  manager.setEnabled(project, false);
  assert.equal(manager.available.find((item) => item.name === "review")?.path, global);
  const restored = new SkillsManager({ home, cwd, trusted: true, userHome });
  assert.equal(restored.items.find((item) => item.path === project)?.enabled, false);
  const untrusted = new SkillsManager({ home, cwd, trusted: false, userHome });
  assert.deepEqual(untrusted.available.map((item) => item.name), ["review"]);
  assert.ok(untrusted.available.every((item) => item.scope === "user"));
  manager.setEnabled(global, false);
  await assert.rejects(manager.prepare("/skill:review inspect"), /disabled/);
  await assert.rejects(manager.prepare("Use @skill:review"), /disabled/);
  await assert.rejects(manager.prepare("@skill:missing"), /unavailable/);
});

test("Skill input snapshots, multiple selections, file mentions, and resource boundaries", async (t) => {
  const root = await mkdtemp(join(tmpdir(), "arkcode-skill-input-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const cwd = join(root, "workspace"); await mkdir(cwd);
  const dir = join(root, ".agents", "skills", "review"); await mkdir(join(dir, "references"), { recursive: true });
  const file = join(dir, "SKILL.md");
  await writeFile(file, "---\nname: review\ndescription: Review changes.\n---\nOriginal Skill body.");
  const manual = join(root, ".agents", "skills", "manual"); await mkdir(manual);
  await writeFile(join(manual, "SKILL.md"), "---\nname: manual\ndescription: Only when selected.\ndisable-model-invocation: true\n---\nManual Skill body.");
  await writeFile(join(dir, "references", "guide.md"), "Reference evidence.");
  const manager = new SkillsManager({ home: join(root, "config"), cwd, trusted: false, userHome: root });
  const input = "Use @skill:review and @skill:manual with @input.txt"; await writeFile(join(cwd, "input.txt"), "Input.");
  const mentions = await prepareAttachments(input, [], cwd, false);
  const prepared = await manager.prepare(mentions.text);
  assert.equal(prepared, `User activated the skill "review". Follow the loaded skill instructions.\n\n<skill-loaded name="review">\nOriginal Skill body.\n</skill-loaded>\n\nUser activated the skill "manual". Follow the loaded skill instructions.\n\n<skill-loaded name="manual">\nManual Skill body.\n</skill-loaded>\n\n${input}`);
  assert.equal(await manager.prepare("/skill:review @skill:manual @skill:review inspect"), prepared.slice(0, -input.length) + "/skill:review @skill:manual @skill:review inspect");
  await writeFile(file, "---\nname: review\ndescription: Review changes.\n---\nUpdated Skill body.");
  assert.match(prepared, /Original Skill body/);
  assert.match(prepared, /Manual Skill body/);
  assert.doesNotMatch(prepared, /Updated Skill body/);
  assert.equal(displayUserText(prepared), input);
  assert.equal(displayUserText(`<skill name="review" location="${file}">\nOriginal Skill body.\n</skill>\n\n${input}`), input);
  assert.match(await manager.prepare("/skill:review inspect"), /Updated Skill body/);
  assert.equal(await manager.prepare("Example: `@skill:missing`"), "Example: `@skill:missing`");
  assert.equal(await manager.prepare("```\n@skill:missing\n```"), "```\n@skill:missing\n```");
  await assert.rejects(manager.prepare("@skill:"), /Use @skill:name/);
  await assert.rejects(manager.prepare("/skill:"), /Use \/skill:name/);
  assert.equal((await manager.read(cwd, join(dir, "references", "guide.md")))?.toString(), "Reference evidence.");
  await writeFile(join(root, "private.txt"), "Private.");
  await symlink(root, join(dir, "escape"), process.platform === "win32" ? "junction" : "dir");
  await assert.rejects(manager.read(cwd, join(dir, "escape", "private.txt")), /outside/);
  assert.equal(await manager.read(cwd, join(root, "private.txt")), undefined);
  manager.setEnabled("review", false);
  await assert.rejects(manager.read(cwd, file), /disabled/);
  assert.match(await readFile(join(root, "config", "skills.json"), "utf8"), /disabledPaths/);
});

test("@ searches Skills alongside files and explicit Skill prefix avoids file ambiguity", async (t) => {
  const cwd = await mkdtemp(join(tmpdir(), "arkcode-skill-search-"));
  t.after(() => rm(cwd, { recursive: true, force: true }));
  await writeFile(join(cwd, "review.txt"), "File.");
  const provider = new WorkspaceAutocompleteProvider(cwd, () => [], () => [{ name: "review", description: "Inspect a patch", scope: "user" }]);
  const suggestions = await provider.getSuggestions(["@rev"], 0, 4, { signal: new AbortController().signal });
  assert.ok(suggestions);
  assert.deepEqual(suggestions.items.map((item) => item.value), ["@skill:review", "@review.txt"]);
  assert.equal(stripTerminalSequences(suggestions.items[0]?.label ?? ""), "Skill · review");
  const description = await provider.getSuggestions(["@patch"], 0, 6, { signal: new AbortController().signal });
  assert.equal(description?.items[0]?.value, "@skill:review");
  const explicit = await provider.getSuggestions(["@skill:rev"], 0, 10, { signal: new AbortController().signal });
  assert.deepEqual(explicit?.items.map((item) => item.value), ["@skill:review"]);
});
